"""Constructs a PyTorch module from a sampled architecture dictionary."""
import torch.nn as nn
import torch.nn.functional as F

from .space import SPACE

ACTS = {
    "relu": nn.ReLU,
    "relu6": nn.ReLU6,
    "silu": nn.SiLU,
    "gelu": nn.GELU,
}


class ConvBlock(nn.Module):
    def __init__(self, cin, cout, kernel, act, stride):
        super().__init__()
        self.net = nn.Sequential(
            nn.Conv2d(cin, cout, kernel, stride, kernel // 2, bias=False),
            nn.BatchNorm2d(cout),
            ACTS[act](),
        )

    def forward(self, x):
        return self.net(x)


class DepthwiseSeparableBlock(nn.Module):
    def __init__(self, cin, cout, kernel, act, stride):
        super().__init__()
        self.net = nn.Sequential(
            nn.Conv2d(cin, cin, kernel, stride, kernel // 2, groups=cin, bias=False),
            nn.BatchNorm2d(cin),
            ACTS[act](),
            nn.Conv2d(cin, cout, 1, bias=False),
            nn.BatchNorm2d(cout),
            ACTS[act](),
        )

    def forward(self, x):
        return self.net(x)


class EdgeCNN(nn.Module):
    """Network generated by the architecture generator."""

    def __init__(self, arch, num_classes):
        super().__init__()
        self.resolution = arch["resolution"]
        layers = [ConvBlock(3, arch["stem"], 3, "relu", 1)]
        channels = arch["stem"]

        for stage in arch["stages"]:
            block_type = DepthwiseSeparableBlock if stage["block"] == "dwsep" else ConvBlock
            for i in range(stage["blocks"]):
                stride = stage["stride"] if i == 0 else 1
                layers.append(block_type(channels, stage["channels"],
                                         stage["kernel"], stage["act"], stride))
                channels = stage["channels"]

        self.features = nn.Sequential(*layers)
        self.pool = nn.AdaptiveAvgPool2d(1)
        self.classifier = nn.Sequential(
            nn.Flatten(),
            nn.Linear(channels, arch["head"]),
            nn.ReLU(),
            nn.Linear(arch["head"], num_classes),
        )

    def forward(self, x, return_feats=False):
        if self.resolution != x.shape[-1]:
            x = F.interpolate(x, size=(self.resolution, self.resolution), mode="bilinear",
                              align_corners=False)
        feats = self.features(x)
        logits = self.classifier(self.pool(feats))
        if return_feats:
            return logits, feats
        return logits
